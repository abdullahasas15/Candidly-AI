#!/usr/bin/env python3
"""Inspects SQLAlchemy models and writes docs/SCHEMA.md."""

import inspect
import sys
from pathlib import Path
from sqlalchemy.inspection import inspect as sa_inspect

# Add repo root to path
ROOT_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT_DIR))

from backend.app.database import Base
import backend.app.models as app_models


def generate_schema_doc() -> str:
    # Build map of __tablename__ to model class
    table_to_model = {}
    for attr_name in dir(app_models):
        attr = getattr(app_models, attr_name)
        if isinstance(attr, type) and issubclass(attr, Base) and attr != Base:
            if hasattr(attr, "__tablename__"):
                table_to_model[attr.__tablename__] = attr

    doc = []
    doc.append("# Candidly AI Voice Interview Platform - Database Schema Reference")
    doc.append("")
    doc.append("> **Note**: This file is auto-generated by `scripts/dump_schema_doc.py`. "
               "Always trust `backend/app/models.py` and `docs/SCHEMA.md` over any stale design documents.")
    doc.append("")
    doc.append("## Table of Contents")
    doc.append("")
    
    sorted_tables = sorted(Base.metadata.tables.keys())
    for tname in sorted_tables:
        model = table_to_model.get(tname)
        cname = model.__name__ if model else "N/A"
        doc.append(f"- [{tname} (`{cname}`)](#{tname})")
    doc.append("")
    doc.append("---")
    doc.append("")

    for tname in sorted_tables:
        table = Base.metadata.tables[tname]
        model = table_to_model.get(tname)
        cname = model.__name__ if model else "N/A"
        docstring = inspect.getdoc(model) if model else None

        doc.append(f"### <a id=\"{tname}\"></a> `{tname}` (Model: `{cname}`)")
        doc.append("")
        if docstring:
            doc.append(f"*{docstring.strip()}*")
            doc.append("")

        doc.append("| Column | Type | Nullable | Primary Key | Default / Server Default | Foreign Key | Indexes / Notes |")
        doc.append("|---|---|---|---|---|---|---|")

        for col in table.columns:
            c_name = col.name
            c_type = str(col.type)
            c_nullable = "YES" if col.nullable else "NO"
            c_pk = "✓" if col.primary_key else ""
            
            default_val = ""
            if col.default is not None:
                arg = getattr(col.default, "arg", None)
                if callable(arg):
                    default_val = f"`{arg.__name__}()`" if hasattr(arg, "__name__") else "`<callable>`"
                else:
                    default_val = f"`{arg}`"
            elif col.server_default is not None:
                default_val = f"`{col.server_default.arg}`"

            fk_str = ""
            if col.foreign_keys:
                fks = [f"`{fk.target_fullname}` (ondelete: {fk.ondelete or 'RESTRICT'})" for fk in col.foreign_keys]
                fk_str = ", ".join(fks)

            notes = []
            if col.index:
                notes.append("Indexed")
            if col.unique:
                notes.append("Unique")
            notes_str = ", ".join(notes) if notes else "-"

            doc.append(f"| `{c_name}` | `{c_type}` | {c_nullable} | {c_pk} | {default_val or '-'} | {fk_str or '-'} | {notes_str} |")

        doc.append("")

        # Indexes & Constraints
        if table.indexes:
            doc.append("**Indexes:**")
            for idx in table.indexes:
                cols = ", ".join(f"`{c.name}`" for c in idx.columns)
                unique = " (Unique)" if idx.unique else ""
                doc.append(f"- `{idx.name}`{unique} on ({cols})")
            doc.append("")

        if model:
            mapper = sa_inspect(model)
            relationships = mapper.relationships
            if relationships:
                doc.append("**Relationships:**")
                for rel in relationships:
                    target_model = rel.target.name if hasattr(rel.target, "name") else rel.argument
                    direction = rel.direction.name
                    doc.append(f"- `{rel.key}` -> `{target_model}` ({direction})")
                doc.append("")

        doc.append("---")
        doc.append("")

    return "\n".join(doc)


def main():
    doc_content = generate_schema_doc()
    docs_dir = ROOT_DIR / "docs"
    docs_dir.mkdir(parents=True, exist_ok=True)
    schema_file = docs_dir / "SCHEMA.md"
    schema_file.write_text(doc_content, encoding="utf-8")
    print(f"✓ Schema documentation written to: {schema_file} ({len(doc_content)} bytes)")


if __name__ == "__main__":
    main()
